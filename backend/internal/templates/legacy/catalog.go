// Package legacy keeps every listing of the old aidir3 Design template library
// reachable as a variation of one of the distinct designs ported from it.
//
// The old gallery listed 199,605 templates: a few hundred layouts multiplied
// by copy briefs, formats and palettes. The port carried one representative
// per layout over as a built-in template ("a3-lib-*", the base designs); the
// rest live here as a compact catalogue (catalog.json.gz, one row per listing
// over shared tables of briefs, layouts and formats) and are built on demand:
// engine.js, the old site's own generator plus the port converter and the spec
// compiler bundled for goja, rebuilds a listing from its row and returns an
// ordinary template and design file. Both files are generated by
// scripts/aidir3/legacy/build.mjs and committed.
//
// Nothing here touches the database: the catalogue is read-only and embedded,
// loaded on first use so it costs nothing at startup.
package legacy

import (
	"bytes"
	"compress/gzip"
	_ "embed"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"sort"
	"strings"
	"sync"
)

//go:embed catalog.json.gz
var catalogGz []byte

// IDPrefix marks a variation template id: "lv-" + the old library's listing id.
const IDPrefix = "lv-"

// IsID reports whether a template id names a variation.
func IsID(id string) bool { return strings.HasPrefix(id, IDPrefix) && len(id) > len(IDPrefix) }

// ErrNotFound is returned for an id that names no listing.
var ErrNotFound = errors.New("variation not found")

type format struct {
	ID    string `json:"id"`
	Label string `json:"label"`
	W     int    `json:"w"`
	H     int    `json:"h"`
}

type base struct {
	ID         string `json:"id"`
	Title      string `json:"title"`
	Source     string `json:"source"`
	Layout     string `json:"layout"`
	Label      string `json:"label"`
	Collection string `json:"collection"`
}

type layout struct {
	K  string `json:"k"`
	ID string `json:"id"`
	DS *int   `json:"ds,omitempty"`
}

type brief struct {
	S     string   `json:"s"`
	ID    string   `json:"id"`
	Label string   `json:"label"`
	Brand string   `json:"brand"`
	Cat   string   `json:"cat"`
	Tags  []string `json:"tags"`
}

type columns struct {
	K    []int8  `json:"k"`
	L    []int16 `json:"l"`
	B    []int16 `json:"b"`
	F    []int8  `json:"f"`
	CW   []int8  `json:"cw"`
	S    []int16 `json:"s"`
	Pre  []int8  `json:"pre"`
	C    []int8  `json:"c"`
	Base []int16 `json:"base"`
	SC   []int32 `json:"sc"`
}

type catalog struct {
	Listed     int      `json:"listed"`
	Kinds      []string `json:"kinds"`
	Formats    []format `json:"formats"`
	StudioCats []string `json:"studioCats"`
	Cats       []string `json:"cats"`
	Bases      []base   `json:"bases"`
	Layouts    []layout `json:"layouts"`
	Briefs     []brief  `json:"briefs"`
	Suffixes   []string `json:"suffixes"`
	Rows       columns  `json:"rows"`

	byID     map[string]int32
	baseByID map[string]int
	perBase  [][]int32
}

var (
	catOnce sync.Once
	cat     *catalog
	catErr  error
)

// load parses the embedded catalogue once.
func load() (*catalog, error) {
	catOnce.Do(func() {
		zr, err := gzip.NewReader(bytes.NewReader(catalogGz))
		if err != nil {
			catErr = fmt.Errorf("legacy catalogue: %w", err)
			return
		}
		raw, err := io.ReadAll(zr)
		if err != nil {
			catErr = fmt.Errorf("legacy catalogue: %w", err)
			return
		}
		var c catalog
		if err := json.Unmarshal(raw, &c); err != nil {
			catErr = fmt.Errorf("legacy catalogue: %w", err)
			return
		}
		n := len(c.Rows.K)
		for _, l := range [][]int{{len(c.Rows.L)}, {len(c.Rows.B)}, {len(c.Rows.F)}, {len(c.Rows.CW)}, {len(c.Rows.S)}, {len(c.Rows.Pre)}, {len(c.Rows.C)}, {len(c.Rows.Base)}, {len(c.Rows.SC)}} {
			if l[0] != n {
				catErr = errors.New("legacy catalogue: columns differ in length")
				return
			}
		}
		c.baseByID = make(map[string]int, len(c.Bases))
		for i, b := range c.Bases {
			c.baseByID[b.ID] = i
		}
		c.perBase = make([][]int32, len(c.Bases))
		c.byID = make(map[string]int32, n)
		for i := 0; i < n; i++ {
			c.perBase[c.Rows.Base[i]] = append(c.perBase[c.Rows.Base[i]], int32(i))
			c.byID[c.oldID(i)] = int32(i)
		}
		cat = &c
	})
	return cat, catErr
}

func (c *catalog) kind(i int) string { return c.Kinds[c.Rows.K[i]] }

func (c *catalog) brief(i int) *brief {
	if b := c.Rows.B[i]; b >= 0 {
		return &c.Briefs[b]
	}
	return nil
}

// oldID rebuilds the old library's listing id from a row (the exporter checks
// every row against the id the old library gave it).
func (c *catalog) oldID(i int) string {
	l := c.Layouts[c.Rows.L[i]].ID
	f := c.Formats[c.Rows.F[i]].ID
	cw := ""
	if n := c.Rows.CW[i]; n > 0 {
		cw = fmt.Sprintf("-c%d", n+1)
	}
	b := c.brief(i)
	switch c.kind(i) {
	case "hand":
		return l
	case "thumb":
		return "g-yt-" + b.ID + "-" + l + "-" + f + cw
	case "brand":
		return "g-" + b.ID + "-brand-" + l + "-" + f
	case "card":
		return "g-" + b.ID + "-card-" + l + "-" + f + cw
	default:
		return "g-" + b.ID + "-" + l + "-" + f + cw
	}
}

// name is the listing's name in the old gallery.
func (c *catalog) name(i int) string {
	s := c.Suffixes[c.Rows.S[i]]
	b := c.brief(i)
	switch c.Rows.Pre[i] {
	case 1:
		return b.Label + " · " + s
	case 2:
		return b.Brand + " · " + s
	}
	return s
}

// Variation is the list view of one listing.
type Variation struct {
	ID         string   `json:"id"`
	Title      string   `json:"title"`
	BaseID     string   `json:"baseId"`
	Format     string   `json:"format"`
	FormatName string   `json:"formatLabel"`
	Width      int      `json:"width"`
	Height     int      `json:"height"`
	Niche      string   `json:"niche,omitempty"`
	Categories []string `json:"categories"`
}

func (c *catalog) view(i int) Variation {
	f := c.Formats[c.Rows.F[i]]
	v := Variation{
		ID: IDPrefix + c.oldID(i), Title: c.name(i), BaseID: c.Bases[c.Rows.Base[i]].ID,
		Format: f.ID, FormatName: f.Label, Width: f.W, Height: f.H, Categories: c.studioCats(i),
	}
	if b := c.brief(i); b != nil {
		v.Niche = b.Label
	}
	return v
}

func (c *catalog) studioCats(i int) []string {
	out := []string{}
	m := c.Rows.SC[i]
	for k, name := range c.StudioCats {
		if m&(1<<k) != 0 {
			out = append(out, name)
		}
	}
	return out
}

// Query filters the variation list. Empty fields do not constrain.
type Query struct {
	Text     string
	BaseID   string
	Category string // a built-in template category ("flyers", "resumes", ...)
	Format   string // an old format id ("ig-post", "flyer", ...)
	Offset   int
	Limit    int
}

// Page is one page of variations plus the total that match.
type Page struct {
	Items  []Variation `json:"items"`
	Total  int         `json:"total"`
	Offset int         `json:"offset"`
	Limit  int         `json:"limit"`
}

// words splits a search into lower-case words.
func words(q string) []string {
	return strings.FieldsFunc(strings.ToLower(q), func(r rune) bool {
		return !(r >= 'a' && r <= 'z' || r >= '0' && r <= '9' || r == '&' || r > 127)
	})
}

// List returns one page of variations matching q, in catalogue order (the old
// gallery's order); with text, listings whose name has the words lead.
func List(q Query) (Page, error) {
	c, err := load()
	if err != nil {
		return Page{}, err
	}
	if q.Limit <= 0 || q.Limit > 200 {
		q.Limit = 48
	}
	if q.Offset < 0 {
		q.Offset = 0
	}
	cand := c.candidates(q)
	ws := words(q.Text)
	var hits []int32
	if len(ws) == 0 {
		hits = cand
	} else {
		m := c.matcher(ws)
		var strong, weak []int32
		for _, i := range cand {
			switch m(int(i)) {
			case 2:
				strong = append(strong, i)
			case 1:
				weak = append(weak, i)
			}
		}
		hits = append(strong, weak...)
	}
	p := Page{Total: len(hits), Offset: q.Offset, Limit: q.Limit, Items: []Variation{}}
	for k := q.Offset; k < len(hits) && k < q.Offset+q.Limit; k++ {
		p.Items = append(p.Items, c.view(int(hits[k])))
	}
	return p, nil
}

// candidates applies the structured filters (base, category, format).
func (c *catalog) candidates(q Query) []int32 {
	var pool []int32
	if q.BaseID != "" {
		bi, ok := c.baseByID[q.BaseID]
		if !ok {
			return nil
		}
		pool = c.perBase[bi]
	}
	catBit := int32(0)
	if q.Category != "" {
		for k, name := range c.StudioCats {
			if name == q.Category {
				catBit = 1 << k
			}
		}
		if catBit == 0 {
			return nil
		}
	}
	fi := -1
	if q.Format != "" {
		for k, f := range c.Formats {
			if f.ID == q.Format {
				fi = k
			}
		}
		if fi < 0 {
			return nil
		}
	}
	keep := func(i int) bool {
		return (catBit == 0 || c.Rows.SC[i]&catBit != 0) && (fi < 0 || int(c.Rows.F[i]) == fi)
	}
	out := []int32{}
	if pool != nil {
		for _, i := range pool {
			if keep(int(i)) {
				out = append(out, i)
			}
		}
		return out
	}
	for i := range c.Rows.K {
		if keep(i) {
			out = append(out, int32(i))
		}
	}
	return out
}

// matcher answers, per row, 2 when every word is in the listing's name, 1
// when every word is somewhere in its words (name, niche, brief tags, format,
// category, base design), 0 otherwise. The tables are matched once per word,
// so a search over every listing stays a pass over small integers.
func (c *catalog) matcher(ws []string) func(i int) int {
	type tbl struct{ suffix, brief, briefName, format, cat, base []bool }
	per := make([]tbl, len(ws))
	has := func(s, w string) bool { return strings.Contains(strings.ToLower(s), w) }
	for k, w := range ws {
		t := tbl{make([]bool, len(c.Suffixes)), make([]bool, len(c.Briefs)), make([]bool, len(c.Briefs)), make([]bool, len(c.Formats)), make([]bool, len(c.Cats)), make([]bool, len(c.Bases))}
		for i, s := range c.Suffixes {
			t.suffix[i] = has(s, w)
		}
		for i, b := range c.Briefs {
			t.briefName[i] = has(b.Label, w) || has(b.Brand, w)
			t.brief[i] = t.briefName[i] || has(b.Cat, w) || has(strings.Join(b.Tags, " "), w)
		}
		for i, f := range c.Formats {
			t.format[i] = has(f.Label, w) || has(f.ID, w)
		}
		for i, s := range c.Cats {
			t.cat[i] = has(s, w)
		}
		for i, b := range c.Bases {
			t.base[i] = has(b.Title, w)
		}
		per[k] = t
	}
	return func(i int) int {
		inName := true
		bi := int(c.Rows.B[i])
		for _, t := range per {
			nameHit := t.suffix[c.Rows.S[i]] || (bi >= 0 && t.briefName[bi])
			if !nameHit {
				inName = false
				if !(bi >= 0 && t.brief[bi]) && !t.format[c.Rows.F[i]] && !t.cat[c.Rows.C[i]] && !t.base[c.Rows.Base[i]] {
					return 0
				}
			}
		}
		if inName {
			return 2
		}
		return 1
	}
}

// BaseCount is how many variations a base design has.
type BaseCount struct {
	BaseID string `json:"baseId"`
	Title  string `json:"title"`
	Count  int    `json:"count"`
	// Sample is the first variation, the card shown for a base design that is
	// not itself a built-in template.
	Sample string `json:"sample"`
}

// Summary is the catalogue at a glance.
type Summary struct {
	Total int         `json:"total"`
	Bases []BaseCount `json:"bases"`
}

// Summarize counts variations per base design (bases with the most first).
func Summarize() (Summary, error) {
	c, err := load()
	if err != nil {
		return Summary{}, err
	}
	s := Summary{Total: len(c.Rows.K)}
	for bi, rows := range c.perBase {
		if len(rows) == 0 {
			continue
		}
		s.Bases = append(s.Bases, BaseCount{BaseID: c.Bases[bi].ID, Title: c.Bases[bi].Title, Count: len(rows), Sample: IDPrefix + c.oldID(int(rows[0]))})
	}
	sort.SliceStable(s.Bases, func(a, b int) bool { return s.Bases[a].Count > s.Bases[b].Count })
	return s, nil
}

// Lookup returns the list view of one variation.
func Lookup(id string) (Variation, error) {
	c, err := load()
	if err != nil {
		return Variation{}, err
	}
	i, ok := c.byID[strings.TrimPrefix(id, IDPrefix)]
	if !IsID(id) || !ok {
		return Variation{}, ErrNotFound
	}
	return c.view(int(i)), nil
}

// recipe is what engine.js needs to rebuild a listing.
type recipe struct {
	K      string `json:"k"`
	ID     string `json:"id"`
	Set    string `json:"set,omitempty"`
	Brief  string `json:"brief,omitempty"`
	Layout string `json:"layout"`
	Format string `json:"format"`
	CW     int    `json:"cw"`
	DS     *int   `json:"ds,omitempty"`
}

type engineReq struct {
	Recipe recipe `json:"recipe"`
	ID     string `json:"id"`
	Title  string `json:"title"`
	Base   base   `json:"base"`
}

func (c *catalog) request(i int) engineReq {
	l := c.Layouts[c.Rows.L[i]]
	r := recipe{K: c.kind(i), ID: c.oldID(i), Layout: l.ID, Format: c.Formats[c.Rows.F[i]].ID, CW: int(c.Rows.CW[i]), DS: l.DS}
	if b := c.brief(i); b != nil {
		r.Brief = b.ID
		if b.S != "t" {
			r.Set = b.S
		}
	}
	return engineReq{Recipe: r, ID: IDPrefix + r.ID, Title: c.name(i), Base: c.Bases[c.Rows.Base[i]]}
}
